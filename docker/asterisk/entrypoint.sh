#!/usr/bin/env bash
set -euo pipefail

SIDECAR_PID=""
ASTERISK_PID=""
ASTERISK_CONFIG_DIR="${ASTERISK_CONFIG_DIR:-/etc/asterisk}"

# Render config that depends on installation settings in .env. These files are
# derived from the environment on every start, so .env stays the single source.
: "${ARI_USER:?ARI_USER is not set}" "${ARI_PASS:?ARI_PASS is not set}"
: "${AMI_USER:?AMI_USER is not set}" "${AMI_PASS:?AMI_PASS is not set}"
export AMI_PORT="${AMI_PORT:-5038}"
export SIP_PORT="${SIP_PORT:-5080}"
export ARI_BIND_ADDR="${ARI_BIND_ADDR:-127.0.0.1}"
TEMPLATE_DIR="${ASTERISK_TEMPLATE_DIR:-/usr/local/share/callytics/asterisk-templates}"
envsubst '${ARI_USER} ${ARI_PASS}' < "${TEMPLATE_DIR}/ari.conf.tmpl" > "${ASTERISK_CONFIG_DIR}/ari.conf"
envsubst '${AMI_PORT} ${AMI_USER} ${AMI_PASS}' < "${TEMPLATE_DIR}/manager.conf.tmpl" > "${ASTERISK_CONFIG_DIR}/manager.conf"
envsubst '${SIP_PORT}' < "${TEMPLATE_DIR}/pjsip_transports.conf.tmpl" > "${ASTERISK_CONFIG_DIR}/pjsip_transports.conf"
envsubst '${ARI_BIND_ADDR}' < "${TEMPLATE_DIR}/http.conf.tmpl" > "${ASTERISK_CONFIG_DIR}/http.conf"
chmod 640 "${ASTERISK_CONFIG_DIR}/ari.conf" "${ASTERISK_CONFIG_DIR}/manager.conf"
echo "[asterisk-entrypoint] generated ari.conf, http.conf (bind ${ARI_BIND_ADDR}), manager.conf (AMI port ${AMI_PORT}) and pjsip_transports.conf (SIP port ${SIP_PORT})"

# Initial rtp.conf from .env. After the first start the backend owns this file
# and regenerates it from the RTP range in the Settings page.
if [ ! -f "${ASTERISK_CONFIG_DIR}/rtp.conf" ]; then
  RTP_START="${RTP_PORT_START:-10000}"
  RTP_END="${RTP_PORT_END:-20000}"
  cat > "${ASTERISK_CONFIG_DIR}/rtp.conf" <<RTPCONF
; auto-generated by callytics. Change the RTP range in Settings or via RTP_PORT_START/RTP_PORT_END in .env
[general]
rtpstart=${RTP_START}
rtpend=${RTP_END}
rtcpstats=yes
rtcpinterval=5000
strictrtp=no
icesupport=yes
stunaddr=
RTPCONF
  echo "[asterisk-entrypoint] generated rtp.conf (${RTP_START}-${RTP_END})"
fi

if [ -n "${TZ:-}" ] && [ -f "/usr/share/zoneinfo/${TZ}" ]; then
  ln -snf "/usr/share/zoneinfo/${TZ}" /etc/localtime
  echo "${TZ}" > /etc/timezone
fi

if [ "${TSHARK_ENABLED:-false}" = "true" ]; then
  node /usr/local/bin/capture-sidecar.js &
  SIDECAR_PID=$!
  echo "[asterisk-entrypoint] capture sidecar started (pid=${SIDECAR_PID})"
else
  echo "[asterisk-entrypoint] capture sidecar disabled (TSHARK_ENABLED=${TSHARK_ENABLED:-unset})"
fi

cleanup() {
  if [ -n "${SIDECAR_PID}" ]; then
    kill -TERM "${SIDECAR_PID}" 2>/dev/null || true
    wait "${SIDECAR_PID}" 2>/dev/null || true
    SIDECAR_PID=""
  fi

  if [ -n "${ASTERISK_PID}" ]; then
    kill -TERM "${ASTERISK_PID}" 2>/dev/null || true
    wait "${ASTERISK_PID}" 2>/dev/null || true
    ASTERISK_PID=""
  fi
}

trap cleanup SIGINT SIGTERM

asterisk -f -C /etc/asterisk/asterisk.conf &
ASTERISK_PID=$!

wait "${ASTERISK_PID}"
exit_code=$?

cleanup
exit "${exit_code}"
