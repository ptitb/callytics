export interface RtpRange {
  start: number;
  end: number;
}

export const DEFAULT_RTP_START = 10000;
export const DEFAULT_RTP_END = 20000;
const MIN_PORT = 1024;
const MAX_PORT = 65535;
const MIN_RANGE_WIDTH = 20;

function parsePort(value: string | undefined, fallback: number): number {
  const parsed = Number(value);
  return Number.isInteger(parsed) && parsed > 0 ? parsed : fallback;
}

/** Initial RTP range from the environment (RTP_PORT_START / RTP_PORT_END). */
export function getEnvRtpRange(env: NodeJS.ProcessEnv = process.env): RtpRange {
  const range = {
    start: parsePort(env.RTP_PORT_START, DEFAULT_RTP_START),
    end: parsePort(env.RTP_PORT_END, DEFAULT_RTP_END),
  };
  return validateRtpRange(range) === null
    ? range
    : { start: DEFAULT_RTP_START, end: DEFAULT_RTP_END };
}

/** Returns an error message when the range is unusable, otherwise null. */
export function validateRtpRange({ start, end }: RtpRange): string | null {
  if (!Number.isInteger(start) || !Number.isInteger(end)) {
    return 'RTP ports must be whole numbers';
  }
  if (start < MIN_PORT || end > MAX_PORT) {
    return `RTP ports must be between ${MIN_PORT} and ${MAX_PORT}`;
  }
  if (start % 2 !== 0) {
    return 'RTP start port must be an even number';
  }
  if (end - start < MIN_RANGE_WIDTH) {
    return `RTP range must contain at least ${MIN_RANGE_WIDTH} ports`;
  }
  return null;
}

export function buildRtpConfig({ start, end }: RtpRange): string {
  return [
    '; auto-generated by callytics. Change the RTP range in Settings or via RTP_PORT_START/RTP_PORT_END in .env',
    '[general]',
    `rtpstart=${start}`,
    `rtpend=${end}`,
    'rtcpstats=yes',
    'rtcpinterval=5000',
    'strictrtp=no',
    'icesupport=yes',
    'stunaddr=',
    '',
  ].join('\n');
}
